    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String destination = destinationinput.getText().trim();
        String date        = dateInput.getText().trim();
        String seatsStr    = seatInput.getText().trim();
        String luggageStr  = luggageInput.getText().trim();
        String pickup      = PickupInput.getText().trim();
        java.awt.Window parentWindow = SwingUtilities.getWindowAncestor(this);
        if (destination.isEmpty() || date.isEmpty() || seatsStr.isEmpty()
                || luggageStr.isEmpty() || pickup.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }

        int seats, luggage;
        try {
            seats   = Integer.parseInt(seatsStr);
            luggage = Integer.parseInt(luggageStr);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Seats and Luggage must be numbers.");
            return;
        }

        try {
            Connection conn = ucms.database.DBConnection.getConnection();

            
            PreparedStatement psGet = conn.prepareStatement(
                    "SELECT driver_id FROM driver WHERE student_id = ?");
            psGet.setString(1, currDriver.getStudent_id());
            ResultSet rsGet = psGet.executeQuery();

            if (!rsGet.next()) {
                JOptionPane.showMessageDialog(this, "Driver not found.");
                return;
            }

            String driverId  = rsGet.getString("driver_id");
            String carpoolID = "CP001"; 

            try {
                
                PreparedStatement psCount = conn.prepareStatement("SELECT COUNT(*) AS total FROM carpool");
                ResultSet rsCount = psCount.executeQuery();

                if (rsCount.next()) {
                    int nextIdNumber = rsCount.getInt("total") + 1;

                    
                    carpoolID = String.format("CP%03d", nextIdNumber);
                }
                rsCount.close();
                psCount.close();
            } catch (Exception e) {
                
                System.out.println("Error generating ID, defaulting: " + e.getMessage());
            }
            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate tarikh = LocalDate.parse(date,formatter);
            
            PreparedStatement ps = conn.prepareStatement("INSERT INTO carpool (carpool_id, driver_id, destination, date, "+ "available_seat, luggage_capacity, pickup_location) "
                    + "VALUES (?, ?, ?, ?, ?, ?, ?)");
            ps.setString(1, carpoolID);
            ps.setString(2, driverId);
            ps.setString(3, destination);
            ps.setObject(4, tarikh);
            ps.setInt(5, seats);
            ps.setInt(6, luggage);
            ps.setString(7, pickup);
            int rows = ps.executeUpdate();
            conn.close();

            if (rows > 0) {
                
                Carpool newCarpool = new Carpool(carpoolID, currDriver, destination,date, luggage, seats, pickup);
                currDriver.addCarpoolDriver(newCarpool);

                JOptionPane.showMessageDialog(this,
                        "Trip posted!\nCarpool ID: " + carpoolID);
                if (parentWindow != null) {
                    parentWindow.dispose();
                }
            }

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed


